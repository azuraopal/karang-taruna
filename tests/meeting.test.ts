import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createAgendaStorage, createAgendaJsonFile } from '../server/agendaStorage';
import { emptyMeetingDetails } from '../src/utils/meeting';
import { requestApp } from './http';

const directory = mkdtempSync(join(tmpdir(), 'katar-meeting-'));
process.env.KATAR_STORAGE = 'json';
process.env.DEV_DB_FILE = join(directory, 'data.json');
const storage = await import('../server/storage');
const { apiApp } = await import('../server/apiApp');
let cookie = '';
test('meeting endpoints require a session and enforce origin', async () => {
  assert.equal((await requestApp(apiApp, '/api/agenda/unknown')).status, 401);
  const login = await requestApp(apiApp, '/api/auth/login', 'POST', { username: 'admin', password: 'katar2026' });
  assert.equal(login.status, 200);
  cookie = login.headers.get('set-cookie')!.split(';')[0];
  assert.equal((await requestApp(apiApp, '/api/agenda/unknown', 'PUT', emptyMeetingDetails(), cookie, { origin: 'https://other.invalid' })).status, 403);
});
test('same-day meetings isolate attendance, minutes, deletes and revisions', async () => {
  const a = await storage.agendaStorage.create({ title: 'Rapat A', date: '2026-10-08' });
  const b = await storage.agendaStorage.create({ title: 'Rapat B', date: '2026-10-08' });
  const member = await storage.createTim({ nama: 'Anggota Uji', jabatan: 'Ketua', divisi: 'Pengurus Harian', fotoUrl: '', bio: '' });
  const path = (id: string) => `/api/agenda/${id}/attendance`;
  const put = await requestApp(apiApp, `${path(a.id)}/${member.id}`, 'PUT', { status: 'hadir' }, cookie);
  assert.equal(put.status, 200);
  assert.equal((await put.json()).rapatId, a.id);
  assert.equal((await (await requestApp(apiApp, path(a.id), 'GET', undefined, cookie)).json()).records.length, 1);
  assert.equal((await (await requestApp(apiApp, path(b.id), 'GET', undefined, cookie)).json()).records.length, 0);
  const details = { ...emptyMeetingDetails(), topics: [{ id: 'topic-a', title: 'Kas', discussion: 'Pembahasan kas.', decision: 'Dicatat bersama.', owner: 'Bendahara', dueDate: '2026-10-11' }] };
  assert.equal((await requestApp(apiApp, `/api/agenda/${a.id}`, 'PUT', details, cookie)).status, 200);
  assert.equal((await storage.agendaStorage.get(b.id)).details?.topics.length, 0);
  assert.equal((await requestApp(apiApp, `/api/agenda/${a.id}`, 'PUT', details, cookie)).status, 409);
  const saved = await storage.agendaStorage.get(a.id);
  assert.equal((await requestApp(apiApp, `/api/agenda/${a.id}`, 'PUT', { ...saved.details, minutesStatus: 'final' }, cookie)).status, 200);
  assert.equal((await requestApp(apiApp, `/api/agenda/${b.id}`, 'PUT', { ...emptyMeetingDetails(), minutesStatus: 'final' }, cookie)).status, 400);
  await requestApp(apiApp, `${path(b.id)}/${member.id}`, 'PUT', { status: 'izin' }, cookie);
  await requestApp(apiApp, `${path(a.id)}/${member.id}`, 'DELETE', undefined, cookie);
  assert.equal((await storage.getMeetingAttendance(b.id))[0].status, 'izin');
  assert.equal((await storage.getMeetingAttendance(a.id)).length, 0);
  assert.equal((await requestApp(apiApp, '/api/agenda/missing/attendance', 'GET', undefined, cookie)).status, 404);
  assert.equal((await requestApp(apiApp, `${path(a.id)}/missing`, 'PUT', { status: 'hadir' }, cookie)).status, 404);
  assert.equal((await requestApp(apiApp, `${path(a.id)}/${member.id}`, 'PUT', { status: 'bogus' }, cookie)).status, 400);
});
test('legacy attendance is migrated once to existing meetings and never copied to new meetings', async () => {
  const file = join(directory, 'legacy.json');
  writeFileSync(file, JSON.stringify({ agenda: [{ id: 'old', title: 'Rapat Lama', date: '2026-10-07' }], absensi: [{ anggotaId: 'a', tanggal: '2026-10-07', status: 'hadir' }], untouched: { keep: true } }));
  const json = createAgendaJsonFile(file);
  const make = () => createAgendaStorage({ usesPg: async () => false, json, query: async () => { throw Error('Unexpected PG'); } });
  await make().list();
  const added = await make().create({ title: 'Rapat Baru', date: '2026-10-07' });
  const data = JSON.parse(readFileSync(file, 'utf8'));
  assert.deepEqual(data.meetingAttendance, [{ anggotaId: 'a', tanggal: '2026-10-07', status: 'hadir', rapatId: 'old' }]);
  assert.ok(!data.meetingAttendance.some((r: { rapatId: string }) => r.rapatId === added.id));
  assert.deepEqual(data.untouched, { keep: true });
  data.meetingAttendance = [];
  writeFileSync(file, JSON.stringify(data));
  await make().list();
  assert.deepEqual(JSON.parse(readFileSync(file, 'utf8')).meetingAttendance, []);
});
test('an activity owns multiple meetings and unknown groups cannot receive meetings', async () => {
  const created = await requestApp(apiApp, '/api/agenda/groups', 'POST', { title: 'Isra Miraj 2027' }, cookie);
  assert.equal(created.status, 201);
  const group = await created.json();
  const a = await storage.agendaStorage.create({ title: 'Persiapan 1', date: '2026-10-09', groupId: group.id });
  const b = await storage.agendaStorage.create({ title: 'Persiapan 2', date: '2026-10-09', groupId: group.id });
  assert.equal(a.groupId, group.id);
  assert.equal(b.groupId, group.id);
  assert.notEqual(a.id, b.id);
  await assert.rejects(storage.agendaStorage.create({ title: 'Invalid Group', date: '2026-10-09', groupId: 'unknown' }), /Tidak Ditemukan/);
  assert.ok((await (await requestApp(apiApp, '/api/agenda/groups', 'GET', undefined, cookie)).json()).some((g: { id: string }) => g.id === group.id));
});
test('activity report endpoint is protected and excludes meetings and records of other activities', async () => {
  const group = await storage.meetingGroupStorage.create({ title: 'Rekap Kegiatan' });
  const other = await storage.meetingGroupStorage.create({ title: 'Agenda Lain' });
  const member = await storage.createTim({ nama: 'Anggota Rekap', jabatan: 'Anggota', divisi: 'Sosial', fotoUrl: '', bio: '' });
  const meetings = await Promise.all(Array.from({ length: 3 }, (_, i) => storage.agendaStorage.create({ title: `Pertemuan ${i + 1}`, date: '2026-10-08', groupId: group.id })));
  const outside = await storage.agendaStorage.create({ title: 'Rapat Lain', date: '2026-10-08', groupId: other.id });
  for (const meeting of [meetings[0], outside]) assert.equal((await requestApp(apiApp, `/api/agenda/${meeting.id}/attendance/${member.id}`, 'PUT', { status: 'hadir' }, cookie)).status, 200);
  const path = `/api/agenda/groups/${group.id}/report`;
  assert.equal((await requestApp(apiApp, path)).status, 401);
  const response = await requestApp(apiApp, path, 'GET', undefined, cookie);
  assert.equal(response.status, 200);
  const recap = await response.json();
  assert.equal(recap.group.id, group.id);
  assert.deepEqual(new Set(recap.meetings.map((m: { id: string }) => m.id)), new Set(meetings.map(m => m.id)));
  assert.equal(recap.records.length, 1);
  assert.equal(recap.records[0].rapatId, meetings[0].id);
  assert.ok(recap.members.some((m: { id: string }) => m.id === member.id));
  assert.equal((await requestApp(apiApp, '/api/agenda/groups/unknown/report', 'GET', undefined, cookie)).status, 404);
});
